export function getUiLocale(pathname?: string): UiLocale {
  const path = pathname ?? (typeof location === 'undefined' ? '/' : location.pathname)
  if (path === '/zh' || path.startsWith('/zh/')) return 'zh'
  if (path === '/pt' || path.startsWith('/pt/')) return 'pt'
  return 'en'
}
